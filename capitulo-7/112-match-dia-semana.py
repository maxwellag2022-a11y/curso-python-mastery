dia_semama = input("Ingrese una de las opciones (1 - 7): ")

match dia_semama:
    case "1":
        print("El primer dia de la semana es Lunes")
    case "2":
        print("El segundo dia de la semana es Martes")
    case "3":
        print("El tercer dia de la semana es Miercoles")
    case "4":
        print("El cuarto dia de la semana es Jueves")
    case "5":
        print("El quinto dia de la semana es Viernes")
    case "6":
        print("El sexto dia de la semana es Sabado")
    case "7":
        print("El septimo dia de la semana es Domingo")

