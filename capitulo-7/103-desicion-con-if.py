edad = int(input("¿Cual es tu edad?:"))

if 18 <= edad < 30:
    print("Puede entrar 🚶‍♂️✅")
else:
    print("No puede entrar ❌")

if edad >= 18:
    print("Puede beber 🍾✅")
else:
    print("No beber beber ❌")

if edad == 20 or edad == 25:
    print("Tiene entrada Gratis 🎫")
else:
    print("No tiene entrada Gratis ❌ ")